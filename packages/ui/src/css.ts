import { deriveAccent } from './accent.ts'
import { dur, ease } from './motion.ts'
import { accentPresets, mascot, neutrals, semantic } from './palette.ts'
import { radii, shadows, spacing } from './space.ts'
import { fontFamilies, typeScale } from './type.ts'

type Decl = readonly [name: string, value: string]

const kebab = (s: string) => s.replace(/([a-z])([A-Z0-9])/g, '$1-$2').toLowerCase()
const entries = (obj: Record<string, string>, prefix = '--'): Decl[] =>
  Object.entries(obj).map(([k, v]) => [`${prefix}${kebab(k)}`, v])

const lake = accentPresets[0].hex

function accentDecls(theme: 'light' | 'dark'): Decl[] {
  const s = deriveAccent(lake, theme)
  return [
    ['--accent', s.accent],
    ['--accent-hover', s.accentHover],
    ['--accent-press', s.accentPress],
    ['--accent-fill', s.accentFill],
    ['--on-accent', s.onAccent],
    ['--accent-ink', s.accentInk],
  ]
}

/** Tokens that differ between light and dark. Both dark blocks are built from this one list. */
function themeDecls(theme: 'light' | 'dark'): Decl[] {
  return [
    ...entries(neutrals[theme]),
    ...entries(semantic[theme]),
    ...accentDecls(theme),
    ['--shadow-1', shadows[theme].shadow1],
    ['--shadow-2', shadows[theme].shadow2],
  ]
}

/** Derived from the live accent and surface, so they follow theme and user accent changes. */
const mix = (token: string, pct: number, over: string) =>
  `color-mix(in oklab, var(--${token}) ${pct}%, ${over})`

const derivedDecls: Decl[] = [
  ['--accent-soft', mix('accent', 12, 'var(--surface)')],
  ['--accent-softer', mix('accent', 6, 'var(--surface)')],
  ['--accent-ring', mix('accent', 40, 'transparent')],
  ['--info', 'var(--accent)'],
  ['--ok-soft', mix('ok', 12, 'var(--surface)')],
  ['--warn-soft', mix('warn', 12, 'var(--surface)')],
  ['--danger-soft', mix('danger', 12, 'var(--surface)')],
]

const fixedDecls: Decl[] = [
  ...entries(mascot),
  ...spacing.map((s): Decl => [`--space-${s}`, `${s}px`]),
  ...Object.entries(radii).map(([k, v]): Decl => [`--r-${k}`, `${v}px`]),
  ...Object.entries(typeScale).flatMap(([k, t]): Decl[] => [
    [`--fs-${k}`, `${t.size}rem`],
    [`--lh-${k}`, String(t.lineHeight)],
    [`--fw-${k}`, String(t.weight)],
  ]),
  ['--ff-ui', fontFamilies.ui],
  ['--ff-display', fontFamilies.display],
  ['--ff-mono', fontFamilies.mono],
  ...Object.entries(dur).map(([k, v]): Decl => [`--dur-${k}`, `${v}ms`]),
  ['--ease-out', ease.outCss],
]

const block = (selector: string, decls: readonly Decl[], indent = ''): string =>
  [`${indent}${selector} {`, ...decls.map(([n, v]) => `${indent}  ${n}: ${v};`), `${indent}}`].join(
    '\n',
  )

const colorTokens = [
  'bg',
  'surface',
  'surface-2',
  'line',
  'text',
  'text-2',
  'text-3',
  'accent',
  'accent-hover',
  'accent-press',
  'accent-fill',
  'accent-soft',
  'accent-softer',
  'accent-ring',
  'accent-ink',
  'on-accent',
  'info',
  'ok',
  'ok-soft',
  'warn',
  'warn-soft',
  'danger',
  'danger-soft',
  ...Object.keys(mascot).map(kebab),
]

/** Tailwind v4 reads runtime vars through `inline`, so utilities follow theme and accent changes. */
const tailwindTheme: Decl[] = [
  ...colorTokens.map((t): Decl => [`--color-${t}`, `var(--${t})`]),
  ...Object.keys(radii).map((k): Decl => [`--radius-${k}`, `var(--r-${k})`]),
  ['--font-sans', 'var(--ff-ui)'],
  ['--font-display', 'var(--ff-display)'],
  ['--font-mono', 'var(--ff-mono)'],
  ['--ease-out', ease.outCss],
]

export function generateTokensCss(): string {
  const dark = themeDecls('dark')
  return `${[
    '/* Generated by src/generate-tokens.ts from src/*.ts. Do not edit; run `pnpm --filter @faire/ui generate`. */',
    block(':root', [
      ['color-scheme', 'light'],
      ...themeDecls('light'),
      ...derivedDecls,
      ...fixedDecls,
    ]),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', [...dark, ['color-scheme', 'dark']], '  ')}\n}`,
    block(':root[data-theme="dark"]', [...dark, ['color-scheme', 'dark']]),
    block('@theme inline', tailwindTheme),
  ].join('\n\n')}\n`
}
