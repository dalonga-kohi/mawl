import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

export type BlockSource = { version: number; text: string }

const HEADER = /^version: ([1-9][0-9]*)$/

/**
 * Parses one prompt block file. The first line must be `version: <positive integer>`,
 * followed by a blank line and a non-empty body. Anything else is rejected, so a
 * block can never ship without a version to snapshot against.
 */
export function parseBlockSource(id: string, source: string): BlockSource {
  const lines = source.replace(/\r\n/g, '\n').split('\n')
  const match = HEADER.exec(lines[0] ?? '')
  if (!match?.[1]) {
    throw new Error(`block "${id}": first line must be "version: <positive integer>"`)
  }
  if (!Number.isSafeInteger(Number(match[1]))) {
    throw new Error(`block "${id}": version is too large to represent exactly`)
  }
  if (lines[1] !== '') {
    throw new Error(`block "${id}": the version line must be followed by a blank line`)
  }
  const text = lines.slice(2).join('\n').trim()
  if (text === '') throw new Error(`block "${id}": body is empty`)
  return { version: Number(match[1]), text }
}

/** Reads every `*.md` file in `dir` and returns the source of the generated module. */
export function generateBlocksModule(dir: string | URL): string {
  const path = typeof dir === 'string' ? dir : fileURLToPath(dir)
  const ids = readdirSync(path)
    .filter((name) => name.endsWith('.md'))
    .map((name) => name.slice(0, -'.md'.length))
    .sort()
  const entries = ids.map((id) => {
    const block = parseBlockSource(id, readFileSync(join(path, `${id}.md`), 'utf8'))
    return `  ${JSON.stringify(id)}: ${JSON.stringify(block, null, 2).replace(/\n/g, '\n  ')},`
  })
  return [
    '// GENERATED by `pnpm --filter @mawl/core generate` from packages/core/prompts/*.md.',
    '// Do not edit by hand: edit the .md file and regenerate.',
    '',
    'export const BLOCKS = {',
    ...entries,
    '} as const',
    '',
  ].join('\n')
}
